import 'package:flutter/material.dart';

/// The in-app user guide (คู่มือการใช้งาน): one list of topics per role,
/// each with the steps as the screens name them, the situations a teacher
/// or a pupil meets ("use case") and the things worth knowing. The text
/// follows the printed manual in ~/krucheck-manuals, shortened to what fits
/// a phone screen. Kept as plain data so the screen can search it.
class HelpTopic {
  const HelpTopic({
    required this.id,
    required this.title,
    required this.icon,
    required this.intro,
    this.steps = const [],
    this.useCases = const [],
    this.notes = const [],
  });

  final String id;
  final String title;
  final IconData icon;

  /// One or two sentences on what the feature is for.
  final String intro;

  /// Numbered steps with the button and menu names in «» quotes.
  final List<String> steps;

  /// Situations with how to handle each.
  final List<HelpUseCase> useCases;

  /// Facts and warnings.
  final List<String> notes;

  /// Everything searchable, lower case.
  String get searchText => [
    title,
    intro,
    ...steps,
    for (final u in useCases) ...[u.title, u.story],
    ...notes,
  ].join(' ').toLowerCase();
}

class HelpUseCase {
  const HelpUseCase(this.title, this.story);

  final String title;
  final String story;
}

